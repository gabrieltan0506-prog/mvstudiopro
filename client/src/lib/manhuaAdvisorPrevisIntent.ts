/** 只依据用户自己的明确指令启动试看；模型回答不能授予渲染权限。 */
export function requestsAdvisorPrevisRender(question: string): boolean {
  const text = question.replace(/\s+/g, "");
  // 否定、条件、稍后执行与功能询问均留在讨论态，可再点本页生成按钮。
  if (/(?:不要|不用|不必|别|別|不准|禁止|暂不|暫不|先不|不想|不能)[^。！？!?，,]{0,8}(?:生成|渲染|做|出)(?:[^。！？!?]{0,12})(?:视频|視頻|白模|试看|試看|预览|預覽)/.test(text)) return false;
  if (/(?:等我|等一下|稍后|稍後|以后|以後|如果|假如|先讨论|先討論|只讨论|只討論)/.test(text)) return false;
  if (/[?？]|(?:能否|是否|怎么|怎麼|如何|会不会|會不會|解释|解釋|方法|流程|需要多久|之后|之後)/.test(text)) return false;
  return /(?:生成|渲染|做|出)(?:[^。！？!?]{0,24})(?:试看|試看|白模|预览|預覽|视频|視頻)/.test(text)
    || /(?:白模|视频|視頻)(?:[^。！？!?]{0,12})(?:生成|渲染)(?:出来|出來|一版|一下|给我|給我)/.test(text);
}
