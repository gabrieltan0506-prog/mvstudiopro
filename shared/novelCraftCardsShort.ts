/**
 * 篇幅判定（纯函数）：有总集数（targetEpisodeCount）时，≤ 12 集或文本里出现「短篇 / 短剧 / 短故事」算短篇；
 * 没有总集数就只看文本字样。episodeCount 是单次请求的集数，不是全剧长度，不作信号。
 */
export function isNovelShortForm(input: {
  targetEpisodeCount?: number | null;
  topic?: string | null;
  direction?: string | null;
  advisorMessage?: string | null;
  title?: string | null;
}): boolean {
  const text = [input.topic, input.direction, input.advisorMessage, input.title].filter(Boolean).join("\n");
  const keyword = NOVEL_SHORT_FORM_KEYWORDS.some(k => text.includes(k));
  const total = input.targetEpisodeCount;
  if (typeof total === "number" && Number.isFinite(total) && total > 0) return total <= NOVEL_SHORT_FORM_MAX_EPISODES || keyword;
  return keyword;
}
