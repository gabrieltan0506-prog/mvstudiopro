const short = (c: {
  id: string;
  title: string;
  intro: string;
  tags: string[];
  genres: string[];
  sections: string;
  beats: string[];
  mood: string;
  must: string;
  check: string;
}): NovelCraftShortCardInput => ({
  id: c.id,
  title: c.title,
  intro: c.intro,
  tags: ["短篇", "结构公式", ...c.tags],
  stages: STAGES,
  genres: c.genres,
  form: "short",
  sections: c.sections,
  beats: c.beats,
  body: [
    `适用：短篇整体结构，参考${/^\d/.test(c.sections) ? `${c.sections}节` : "结构"}；篇幅短时相邻节可合并，节数不是硬指标；分集时按因果把节归到各集。`,
    "结构：",
    ...c.beats.map((b, i) => `${i + 1}. ${b}`),
    `情绪曲线：${c.mood}`,
    `必备：${c.must}`,
    `自查：${c.check}`,
  ].join("\n"),
});

