/** 只编译有实际使用场景的卡片；未读视频不会因在输入清单里就成为规则来源。 */
export function selectViralCourseRules(input: { stage: ViralCourseStage; context: string; format?: "图文" | "短视频"; goal?: string | null }) {
  return VIRAL_COURSE_RULES.filter(rule => rule.stages.includes(input.stage)
    && (!rule.formats || (input.format !== undefined && rule.formats.includes(input.format)))
    && (!rule.triggers || rule.triggers.some(term => input.context.includes(term)) || rule.goals?.includes(input.goal || "")));
}

