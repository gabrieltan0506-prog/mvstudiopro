/** 把补充行插到原条目「不做：」「自查：」之前（没有则接在末尾）；原句与第二天补充行都不动。 */
export function withNovelCraftOwnerDay3Supplements<T extends NovelCraftCardInput>(inputs: readonly T[]): T[] {
  for (const id of Object.keys(NOVEL_CRAFT_OWNER_DAY3_SUPPLEMENTS)) {
    if (!inputs.some(c => c.id === id)) throw new Error(`novel craft day3 supplement target missing: ${id}`);
  }
  return inputs.map(c => {
    const extra = NOVEL_CRAFT_OWNER_DAY3_SUPPLEMENTS[c.id];
    if (!extra?.length) return c;
    const lines = c.body.split("\n");
    const tail = lines.findIndex(l => l.startsWith("不做：") || l.startsWith("自查："));
    const at = tail === -1 ? lines.length : tail;
    const added = extra.map(l => `${NOVEL_CRAFT_OWNER_DAY3_SUPPLEMENT_PREFIX}${l}`);
    return { ...c, body: [...lines.slice(0, at), ...added, ...lines.slice(at)].join("\n") };
  });
}
