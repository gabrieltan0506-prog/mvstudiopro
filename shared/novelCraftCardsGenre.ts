/**
 * 题材匹配（确定性，纯字符串，不调模型）：在题材 / 创作方向 / 底本标题文本里找各条目的别名。
 * 被更长命中完全覆盖的命中不计（如「都市修仙」覆盖「修仙」）；每条命中按别名长度计分，题材字段内的命中权重 ×2。
 * 返回得分最高的最多 max 条 id（同分按条目顺序）；都没命中返回空数组。
 */
export function matchNovelCraftGenreCards(
  fields: { topic?: string | null; direction?: string | null; title?: string | null },
  max: number = NOVEL_CRAFT_GENRE_MAX,
  cards: readonly Pick<NovelCraftGenreCardInput, "id" | "genres">[] = NOVEL_CRAFT_GENRE_CARD_INPUTS
): string[] {
  const parts: { text: string; weight: number }[] = [
    { text: fields.topic ?? "", weight: 2 },
    { text: fields.direction ?? "", weight: 1 },
    { text: fields.title ?? "", weight: 1 },
  ];
  const scores = new Map<string, number>();
  for (const { text, weight } of parts) {
    const t = text.toLowerCase();
    if (!t.trim()) continue;
    const hits: { id: string; start: number; end: number }[] = [];
    for (const c of cards) {
      for (const alias of c.genres) {
        const a = alias.toLowerCase();
        if (!a) continue;
        for (let i = t.indexOf(a); i >= 0; i = t.indexOf(a, i + 1)) hits.push({ id: c.id, start: i, end: i + a.length });
      }
    }
    const kept = hits.filter(
      h => !hits.some(o => o !== h && o.start <= h.start && o.end >= h.end && o.end - o.start > h.end - h.start)
    );
    // 同一条目在同一位置只计一次。
    const seen = new Set<string>();
    for (const h of kept) {
      const key = `${h.id}@${h.start}-${h.end}`;
      if (seen.has(key)) continue;
      seen.add(key);
      scores.set(h.id, (scores.get(h.id) ?? 0) + (h.end - h.start) * weight);
    }
  }
  const order = new Map(cards.map((c, i) => [c.id, i]));
  return Array.from(scores.entries())
    .sort((a, b) => b[1] - a[1] || (order.get(a[0]) ?? 0) - (order.get(b[0]) ?? 0))
    .slice(0, Math.max(0, max))
    .map(([id]) => id);
}
