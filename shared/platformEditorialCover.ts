/** 优先采用创作包已有转化目标；没有目标时沿用现有商业意图判定。 */
export function buildPlatformEditorialCoverGuidance(context: string): string {
  const goal = /【封面目标】(成交|获客|关注)/.exec(context)?.[1];
  const commercial = goal ? goal !== "关注" : isMarketingContext(context);
  const purpose = commercial
    ? "【本张封面·购买与行动动机】主视觉先讲清卖什么、谁会用、在什么场景产生什么可见价值，再用摄影层次提升质感；商品/交付不可被人物美照和装饰压成配角。标题提出真实价值，副标承接一个已有的商品差异、交付或可信依据，不自动增加文字行数。获客型只引向已存在的试读、咨询或体验；成交型接具体商品。缺少商品与交付依据时保留待验证建议，不把未确认方案画成现货或承诺。不要只用‘建议收藏’替代本次购买/咨询目的。"
    : "【本张封面·内容阅读动机】突出本题的问题、生活瞬间和内容价值；未指定商业目标，不增添价格、优惠或购买按钮。";
  return `${PLATFORM_EDITORIAL_COVER_GUIDANCE}\n\n${purpose}`;
}
