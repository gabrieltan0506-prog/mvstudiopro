import { afterAll, beforeAll, expect, it, vi } from "vitest";
import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import { verifyTopicCandidates } from "../../shared/topicDigest";
const state=vi.hoisted(()=>({db:null as any}));
vi.mock("../db",()=>({getDb:async()=>state.db}));
import { saveTopicPreference, claimTopicPool, completeTopicPool, deliverTopicPool, listTopicNotifications,
  getTopicNotification, updateTopicNotification, subscribedTopicLanes, topicPoolState, readTopicRecommendationCount } from "./topicDigestStore";
const pg=new PGlite();
beforeAll(async()=>{await pg.exec(`CREATE TABLE users(id integer PRIMARY KEY,role text NOT NULL);INSERT INTO users VALUES(7,'paid'),(8,'free'),(9,'free');CREATE TABLE stripe_customers("userId" integer PRIMARY KEY,plan text);INSERT INTO stripe_customers VALUES(9,'pro')`);state.db=drizzle(pg);},30_000);
afterAll(()=>pg.close());
it("真实数据库覆盖订阅、并发占位、幂等投递、账号隔离、采用隐藏和注销清理",async()=>{
  await saveTopicPreference(7,{enabled:true,lane:"parenting",keywords:"绘本"});
  await saveTopicPreference(8,{enabled:true,lane:"parenting",keywords:"共读"});
  await saveTopicPreference(9,{enabled:false,lane:"parenting",keywords:""});
  expect(await subscribedTopicLanes()).toEqual(["parenting"]);
  const claims=await Promise.all([claimTopicPool("test-pool","parenting",1),claimTopicPool("test-pool","parenting",1)]);
  expect(claims.filter(Boolean)).toHaveLength(1);
  await deliverTopicPool("test-pool");expect(await listTopicNotifications(7)).toHaveLength(0);
  const topics=verifyTopicCandidates({topics:Array.from({length:5},(_,i)=>({title:`测试候选${i}：妈妈道歉后的变化`,angle:"用家长与孩子的真实动作表现情绪修复，避免泛泛的说教或效果承诺。",hook:"妈妈蹲下来时，孩子悄悄递过来一张画。",format:"图文",outline:["先交代矛盾发生的场景","再呈现家长倾听的动作","最后呈现孩子递画的变化"],tags:["亲子"],sourceIds:[]}))},[]);
  await completeTopicPool("test-pool",{id:"test-pool",lane:"parenting",createdAt:new Date().toISOString(),expiresAt:new Date(Date.now()+3600000).toISOString(),topics},{id:"test-only"});
  await Promise.all([deliverTopicPool("test-pool"),deliverTopicPool("test-pool")]);
  expect(await topicPoolState("parenting",1)).toBe("ready");
  expect(await listTopicNotifications(7)).toHaveLength(1);expect(await listTopicNotifications(8)).toHaveLength(1);expect(await listTopicNotifications(9)).toHaveLength(0);
  expect((await getTopicNotification(7,"test-pool")).digest.topics).toHaveLength(2);
  expect((await getTopicNotification(8,"test-pool")).digest.topics).toHaveLength(1);
  expect(await readTopicRecommendationCount(9)).toBe(2);
  await expect(updateTopicNotification(8,"test-pool","adopt","topic-2")).rejects.toThrow("选题不存在");
  await updateTopicNotification(8,"test-pool","dismiss","topic-1");
  expect((await getTopicNotification(8,"test-pool")).digest.topics).toHaveLength(1);
  await expect(getTopicNotification(9,"test-pool")).rejects.toThrow("无权访问");
  await updateTopicNotification(7,"test-pool","read");
  await Promise.all([updateTopicNotification(7,"test-pool","dismiss","topic-1"),updateTopicNotification(7,"test-pool","dismiss","topic-1")]);
  await updateTopicNotification(7,"test-pool","adopt","topic-2");
  state.db=drizzle(pg); // 新连接读回，不依赖React或进程内消息缓存。
  expect(await getTopicNotification(7,"test-pool")).toMatchObject({read:true,dismissed:["topic-1"],adopted:["topic-2"]});
  expect(await getTopicNotification(8,"test-pool")).toMatchObject({read:false,dismissed:["topic-1"],adopted:[]});
  await saveTopicPreference(7,{enabled:true,lane:"ai",keywords:""});
  await claimTopicPool("test-other","ai",1);
  await completeTopicPool("test-other",{id:"test-other",lane:"ai",createdAt:new Date().toISOString(),expiresAt:new Date(Date.now()+3600000).toISOString(),topics},{});
  await deliverTopicPool("test-other");expect(await listTopicNotifications(7)).toHaveLength(1);
  await saveTopicPreference(7,{enabled:true,lane:"parenting",keywords:""});
  await pg.exec("UPDATE users SET role='free' WHERE id=7");
  await saveTopicPreference(8,{enabled:false,lane:"parenting",keywords:""});
  await claimTopicPool("test-next","parenting",2);
  await completeTopicPool("test-next",{id:"test-next",lane:"parenting",createdAt:new Date().toISOString(),expiresAt:new Date(Date.now()+3600000).toISOString(),topics},{});
  await deliverTopicPool("test-next");expect(await listTopicNotifications(8)).toHaveLength(1);
  expect((await getTopicNotification(7,"test-next")).digest.topics).toHaveLength(1);
  expect((await getTopicNotification(7,"test-pool")).digest.topics).toHaveLength(2);
  await pg.exec('DELETE FROM users WHERE id=7');expect(await subscribedTopicLanes()).toEqual([]);
  expect(await listTopicNotifications(7)).toHaveLength(0);
});
