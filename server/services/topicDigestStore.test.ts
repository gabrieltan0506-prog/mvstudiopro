  const raw={topics:Array.from({length:5},(_,i)=>({title:`隔离边界候选${i}的创作测试`,angle:"以实际发生的具体场景编排创作结构，保留可核实的动作与情绪，不编造效果。",hook:"孩子走进房间后轻轻把门关上了。",format:"图文",outline:["建立人物所处的真实场景","展现双方具体的动作回应","用可见的变化收束故事线"],tags:["故事"],sourceIds:[]}))};
